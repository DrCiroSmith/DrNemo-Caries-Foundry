#!/usr/bin/env python3
import pandas as pd
from pathlib import Path
from datetime import datetime

BASE_DIR = Path.home() / "drnemo_research"
RESULTS_DIR = BASE_DIR / "results"
SCORES_FILE = RESULTS_DIR / "master_scores.csv"
ANALYSIS_DIR = RESULTS_DIR / "analysis"
EXPORT_FILE = RESULTS_DIR / "UF_Pitch_Report.md"

def generate_pitch_report():
    if not SCORES_FILE.exists():
        print("No master_scores.csv found.")
        return

    df = pd.read_csv(SCORES_FILE)
    df['Composite_Score'] = pd.to_numeric(df.get('Composite_Score', pd.Series(dtype=float)), errors='coerce')
    if 'Composite_Score' not in df.columns or df['Composite_Score'].isna().all():
        df['pLDDT'] = pd.to_numeric(df['pLDDT'], errors='coerce')
        df['iPTM'] = pd.to_numeric(df['iPTM'], errors='coerce')
        df['Composite_Score'] = (df['pLDDT'] / 100.0) * df['iPTM']
    top_candidates = df[(df['Status'] == 'SUCCESS') & (df['Composite_Score'] > 0.72)].sort_values(by="Composite_Score", ascending=False)
    
    if top_candidates.empty:
        print("No candidates with Composite Score > 0.72 found yet. Keep the orchestrator running!")
        return

    with open(EXPORT_FILE, 'w', encoding='utf-8') as f:
        f.write("# 🏥 High-Confidence Antimicrobial Candidates for Oral Pathogens\n\n")
        f.write(f"**Generated by Dr. Nemo's In-Silico Research Lab** | {datetime.now().strftime('%Y-%m-%d')}\n\n")
        f.write("## Executive Summary\n")
        f.write("This automated report summarizes computationally predicted biomolecular interactions targeting oral pathogens (e.g., *S. mutans*, *P. gingivalis*). Structural viability was determined via OpenFold3 (NVIDIA NIM API), and clinical synthesis was generated via an LLM synthesizer (Ollama or GitHub Copilot Models).\n\n")
        
        for _, row in top_candidates.iterrows():
            job_id = row['Job_ID']
            f.write(f"---\n\n### Candidate: `{job_id}`\n")
            f.write(f"- **pLDDT (Local Confidence):** {row['pLDDT']:.2f}\n")
            f.write(f"- **iPTM (Interface Confidence):** {row['iPTM']:.3f}\n")
            f.write(f"- **Composite Score:** {row['Composite_Score']:.3f} 🏆\n\n")
            
            analysis_path = ANALYSIS_DIR / f"{job_id}.md"
            if analysis_path.exists():
                with open(analysis_path, 'r', encoding='utf-8') as a_file:
                    content = a_file.read()
                    content = content.replace(f"# Clinical Synthesis: {job_id}", "")
                    f.write(f"#### Clinical Synthesis\n{content}\n")
            else:
                f.write("*Clinical synthesis pending.*\n\n")
                
    print(f"✅ Success! Pitch report exported to {EXPORT_FILE.name}")

if __name__ == "__main__":
    generate_pitch_report()
